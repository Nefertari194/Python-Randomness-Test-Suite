def template_non_overlapping(bits, alpha=0.01, verbose=False, template_group=0, template_index=0):
    # 非重叠模板匹配：把序列分块，在每块中用“命中后跳过模板长度”的方式计数，再做卡方检验
    n = len(bits)
    if n <= 0:
        return False, None, {"reason": "数据是空的"}

    group = int(template_group)
    if group < 0:
        group = 0
    if group >= len(_TEMPLATES):
        group = len(_TEMPLATES) - 1
    template_list = _TEMPLATES[group]

    index = int(template_index)
    if index < 0:
        index = 0
    if index >= len(template_list):
        index = len(template_list) - 1
    b = template_list[index]

    m = len(b)
    n_blocks = 8
    # 标准实现里固定分 8 块，这里保持一致（多余的比特直接截掉）
    block_size = int(math.floor(float(n) / float(n_blocks)))
    if block_size <= 0:
        return False, None, {"reason": "分块后块大小为 0"}
    n_used = block_size * n_blocks
    bits = bits[:n_used]

    blocks = []
    for i in range(n_blocks):
        blocks.append(bits[i * block_size : (i + 1) * block_size])

    w = []
    for block in blocks:
        position = 0
        count = 0
        while position <= (block_size - m):
            if block[position : position + m] == b:
                # 非重叠：命中一次后直接跳过模板长度
                position += m
                count += 1
            else:
                position += 1
        w.append(count)

    mu = float(block_size - m + 1) / float(2**m)
    var = float(block_size) * ((1.0 / float(2**m)) - (float((2 * m) - 1) / float(2 ** (2 * m))))
    if var <= 0.0:
        return False, None, {"reason": "参数不太合适，算出来的方差不对"}

    chi_sq = 0.0
    for j in range(n_blocks):
        chi_sq += ((w[j] - mu) ** 2) / var

    p = chi2_sf(chi_sq, n_blocks)
    return p >= alpha, p, None

